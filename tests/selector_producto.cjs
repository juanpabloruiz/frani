const { chromium } = require('playwright');
const fs = require('fs');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({headless:true,channel:'chrome'});
 const page = await browser.newPage();
 const errors=[];page.on('pageerror', e=>errors.push(e.message));
 const root=require('node:path').resolve(__dirname, '..') + '/';
 let html=fs.readFileSync(root+'src/panel/facturas/nueva.php','utf8').replace(/<\?php[\s\S]*?\?>/g,'').replace(/<\?=[\s\S]*?\?>/g,'');
 html=html.replace(/<script src=[\s\S]*?<\/script>/g,'');
 const helper=fs.readFileSync(root+'src/js/selector-producto.js','utf8');
 const fixture=[{id:1,producto:'Caja de biromes azules',precio:120,stock:10},{id:2,producto:'Birome negra',precio:50,stock:null},{id:3,producto:'Lápiz',precio:30,stock:8}];
 html=html.replace('<script>',`<script>${helper}\nwindow.fetch=async()=>({json:async()=>(${JSON.stringify(fixture)})});</script><script>`);
 await page.setContent(html);
 const input=page.getByRole('combobox').first();
 await input.fill('BIROME');
 assert.equal(await page.getByRole('option').count(),2);
 await input.press('ArrowDown');await input.press('Enter');
 assert.equal(await page.locator('select.select-producto').first().inputValue(),'2');
 assert.equal(await page.locator('#total').inputValue(),'50.00');
 assert.equal(await page.getByRole('combobox').count(),2);
 await input.fill('lapiz');
 assert.equal(await page.getByRole('option').count(),1);
 await page.getByRole('option').click();
 assert.equal(await page.locator('#total').inputValue(),'30.00');
 await page.locator('.cantidad').first().fill('3');
 assert.equal(await page.locator('#total').inputValue(),'90.00');
 await input.fill('inexistente');
 assert.equal(await page.getByRole('status').textContent(),'No se encontraron productos');
 assert.equal(await input.evaluate(e=>e.checkValidity()),false);
 assert.equal(await page.locator('#total').inputValue(),'0.00');
 await input.press('Escape');assert.equal(await input.getAttribute('aria-expanded'),'false');
 await input.fill('');assert.equal(await input.evaluate(e=>e.checkValidity()),true);
 await page.evaluate(()=>{const s=document.querySelector('.select-producto');const o=new Option('Producto nuevo','4',true,true);o.dataset.precio='75';s.append(o);s.dispatchEvent(new Event('change'));});
 assert.equal(await input.inputValue(),'Producto nuevo');
 assert.equal(await page.locator('#total').inputValue(),'225.00');
 assert.deepEqual(errors,[]);
 console.log('OK: búsqueda parcial, mayúsculas, tildes, mouse, teclado, cálculo, nueva fila, sin resultados, validación y alta dinámica.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
